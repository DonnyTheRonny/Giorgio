// Deutsche Originaltexte aus dem HTML merken
const nodes = document.querySelectorAll("[data-i18n]");
const de = {};
nodes.forEach(n => { de[n.dataset.i18n] = n.textContent; });
T.de = de;

function setLang(lang) {
  if (!T[lang]) lang = "de";
  nodes.forEach(n => {
    const txt = T[lang][n.dataset.i18n];
    if (txt) n.textContent = txt;
  });
  document.documentElement.lang = lang;
  document.querySelectorAll(".lang button").forEach(b =>
    b.classList.toggle("active", b.dataset.lang === lang));
  try { localStorage.setItem("lang", lang); } catch (e) {}
}

document.querySelectorAll(".lang button").forEach(b =>
  b.addEventListener("click", () => setLang(b.dataset.lang)));

// Sprache: ?lang=en in der URL > gespeicherte Wahl > Browsersprache
let start = new URLSearchParams(location.search).get("lang");
if (!start) { try { start = localStorage.getItem("lang"); } catch (e) {} }
if (!start) {
  const b = (navigator.language || "de").slice(0, 2);
  start = b === "el" ? "el" : b === "de" ? "de" : "en";
}
setLang(start);

